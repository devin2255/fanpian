/**
 * 底部安全净空（vp）—— **贴着页面底部的动作行，其下沿必须留出的空白**。
 *
 * ── 它是什么（不是"又一个边距令牌"）────────────────────────────────────────────
 *   系统手势条（屏幕底部那根横条）会**优先吃掉从底部边缘起始的上滑**。本 App 的
 *   「上墙」按钮就在这一行的最底，而"点上墙变成了回桌面"是这个产品最贵的一种失败。
 *
 *   ── 先澄清一个事实（batch-43 查 SDK 得到，推翻了上一批的模型）─────────────────
 *   在**本工程的默认配置**下，按钮其实**不在**手势条底下：ArkUI 的默认行为是
 *   "页面内容布局在安全区内、不与状态栏/导航栏重叠"。依据有四条：
 *     ① 本仓库 `entryability/EntryAbility.ets` **没有**调 `setWindowLayoutFullScreen` /
 *        `setImmersiveModeEnabledState`，而 SDK 写着这两个都没调时
 *        `getImmersiveModeEnabledState()` 的默认返回是 **false**（= 非沉浸式），
 *        非沉浸式的定义就是"布局避让状态栏与导航栏"（`@ohos.window.d.ts:4504-4505` /
 *        `:8404-8407`）；
 *     ② `common.d.ts:17531-17532` 明说"系统避让区（状态栏、导航栏、挖孔区…）**就是页面容器的
 *        固有安全区内边距**"；组件的 `expandSafeArea` 文档也写着它的生效前提是
 *        "组件边界与安全区域重合"（`common.d.ts:17219-17225`）—— 反过来说，默认状态下组件
 *        本来就在安全区**内**；
 *     ③ 全仓 `git grep expandSafeArea|SafeArea|getWindowAvoidArea|avoidArea` = **零命中**，
 *        所以没有任何一处主动越界；
 *     ④ **真机旁证（本批新给的一条）**：`WallPage` 的地图画布高是**设备上量出来的**
 *        （`box 376×663.71`，task-16 诊断行；它随页面改动变小过：642.57 → 624.86，
 *        删掉诊断行后应回到 ≈638）。把它那三行文字（顶部行 10+文字+8、页脚 11fp+8）算进去，
 *        页面内容高只有 ≈684~743 —— 比屏幕 809.14 **短 66~125vp**（区间来自两行文字是否换行、
 *        行高取 1.0~1.6 倍字号；`boxH` 本身取 634~640）。
 *        **即使把状态栏按最宽的一档取（40vp），底部避让区也 ≥ 26vp**；按常见状态栏取值
 *        （19~38vp）则是 28~106vp。一个状态栏解释不了这 66vp 以上的缺口，
 *        **底部必然也被避让了**，量级与手势导航条（24vp）相当或更大。
 *        （把状态栏与导航条精确拆开要看两行文字的实际高度，本批量不到；但"底部有避让"
 *        这个结论对拆分不敏感，报告 §1.4 有完整区间推导。）
 *   于是"可用区底"= 安全区底：按钮下沿距**屏幕**底 = 手势区高（导航条本身）+ 2vp。
 *
 * ── 那为什么还要这个常量 ───────────────────────────────────────────────────────
 *   因为剩下的净空只有 **2vp**（按钮行高 48 与按钮 44 之差的一半），它**既薄又不是设计出来的**：
 *     · 那 2vp 只是"行高比按钮高 4"的副产品 —— 离"按钮下沿与安全区底重合"只差 2vp。
 *       ⚠️ 上一批读到"距屏底 2vp"这个数，在**页面相对**这一层上其实**是对的**：
 *       `SwipePage` 的**根 Column 没有内边距**（`.padding(S3)` 挂在**顶部行**上，
 *       不是根 Column —— 本批一开始也读错了这一处，复核后更正），所以可用区底就是页面内容底。
 *       错的是后半截：它把**页面底当成了屏底**，于是把"平台已经做了避让"这件事
 *       读成了"按钮压在手势条上"；
 *     · 更要紧的是：真正把按钮挡在手势区外面的，是"平台默认避让"这条**没人写下来的前提**。
 *       只要将来有人给某个节点加 `expandSafeArea`、或把窗口改成沉浸式（一行代码），
 *       这层保护会**当场**消失 —— 而那次改动的作者不会想到要来看刷卡页；
 *     · 手势热区比导航条本身宽，而导航条高度是设备与模式相关的（手势导航 ≈24vp、三键 ≈48vp）。
 *   所以这里把余量显式化：动作行自己留出一段净空。原则取平台自己的规避指南
 *   ——「**宁多勿少**：少留的后果是"按钮点不动/被系统拦"，多留的后果只是底部多一段空白，
 *   用户不会当成错误」（华为开发者文档《安全区域：状态栏／导航条的避让策略》，见报告 §3 引用）。
 *
 * ── 为什么是 32（= 24 + 8）────────────────────────────────────────────────────
 *   24vp = 系统导航条在**手势导航**下的高度（三键导航约 48vp，但那不是"从底部边缘上滑"
 *   那个手势的来源）。取它是因为**它就是"手势条会吃掉多少"这个量本身**，不是挑出来的：
 *   24（手势区高）+ 8（S2，显式写出来的那一点余量）= 32。
 *   加上按钮行自己那 2vp（(48 − 44)/2），按钮下沿距**页面可用区底**的距离 = **34vp**
 *   （改前是 2vp）；距**屏幕**底还要再加平台避让掉的导航条本身。
 *   于是"按钮下沿距屏幕底 ≥ 手势区高度 + 余量"这条要求在**两种**页面底部假设下都成立：
 *   · 若页面已避让（本批查到的默认行为，真机数据也支持）：手势区 + 34；
 *   · 若页面真的铺到屏底（最坏假设）：32 + 2 = 34 ≥ 24（手势区）+ 10（余量）。
 *
 * ── 为什么不走平台接口（取舍的结论；完整对照见报告 §4）──────────────────────────
 *   `window.getWindowAvoidArea(AvoidAreaType.TYPE_NAVIGATION_INDICATOR)` 能给出真实避让高度，
 *   但它**答不了我们真正要问的问题**：它报的是"避让区有多高"，而本工程的页面**已经**避让了它
 *   （默认非沉浸式）—— 把它当额外边距就是**重复避让**（白推 24vp，卡片白矮 24vp）；
 *   反过来若页面是沉浸式的，它又恰好是对的。要区分这两种情形，必须再取窗口矩形与页面根节点的
 *   `globalPosition` 做一次跨坐标系比对（外加 px→vp 换算、异步取窗口句柄、悬浮窗下返回空数组
 *   等边界），而这条路径**本批无法在真机上验证** —— 引入它等于把"确定的多留 8vp"换成
 *   "一个没跑过的分支"。故本批取常量，并把"什么时候该换成平台读取"写在下面。
 *
 * ── 什么情况下需要复核这个数 ────────────────────────────────────────────────────
 *   ① 窗口改成沉浸式（`setWindowLayoutFullScreen(true)` / `setImmersiveModeEnabledState(true)`）
 *      或任何节点加了 `expandSafeArea` —— 页面会伸到手势条下面，本常量要从"余量"升级为
 *      "唯一的净空"，应至少取 48（三键导航那一档）；
 *   ② 目标设备默认用**三键导航**（导航条约 48vp）；
 *   ③ 页面被放进悬浮窗 / 分屏（避让区与手机全屏不同）；
 *   ④ 真机上仍出现"点上墙却回了桌面" —— 继续**加大这个数**；
 *      **不要**去动 `CARD_HEIGHT_RATIO`（会改掉两个真机验过的阈值），
 *      **也不要**把卡片改回小尺寸（会把 batch-42 刚消灭的两条死区带回来）。
 */
export const BOTTOM_SAFE_INSET: number = 32;

